"""The sandboxed document library the assistant works in.

Layout (created on first use):

    <root>/
      Sources/    documents the user imported   (model: read-only)
      Drafts/     everything the assistant writes (model: create / revise)
      .history/   previous versions of every revised draft

Security model
--------------
* The model never handles paths. It sees opaque document IDs (``src-1a2b3c``,
  ``drf-4d5e6f``) and the app maps them to files it found by listing the two
  folders itself. An ID that isn't in that listing is simply "not found".
* Filenames for new drafts are generated by the app from a sanitised title.
* Every path is still passed through ``safe_path()``, which resolves it
  (collapsing ``..``, following links/junctions) and refuses anything that
  ends up outside the library root.
* Sources are never written. Drafts are never overwritten in place without
  the previous version being copied to ``.history/`` first. Nothing is deleted.
* Size and count limits stop a runaway agent from filling the disk.
"""

from __future__ import annotations

import hashlib
import os
import re
import shutil
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

SOURCES = "Sources"
DRAFTS = "Drafts"
HISTORY = ".history"

ALLOWED_SUFFIXES = {".txt", ".md"}
MAX_IMPORT_BYTES = 5_000_000  # per imported file
MAX_DRAFT_BYTES = 200_000  # per draft written by the model
MAX_DRAFTS = 500
WORDS_PER_PAGE = 1200
MAX_SEARCH_RESULTS = 5

RESERVED_NAMES = {
    "CON", "PRN", "AUX", "NUL",
    *(f"COM{i}" for i in range(1, 10)),
    *(f"LPT{i}" for i in range(1, 10)),
}


class LibraryError(Exception):
    """A user- or model-facing error (bad ID, limit reached, etc.)."""


@dataclass(frozen=True)
class Document:
    id: str
    title: str
    kind: str  # "source" or "draft"
    path: Path

    @property
    def filename(self) -> str:
        return self.path.name


# --------------------------------------------------------------------------
# Path safety
# --------------------------------------------------------------------------


def safe_path(root: Path, rel: str) -> Path:
    """Return ``root/rel`` resolved, or raise if it would land outside root."""
    if not isinstance(rel, str) or not rel.strip():
        raise LibraryError("empty path")
    if ":" in rel or rel.startswith(("\\", "/")):
        # drive letters, alternate data streams, absolute and UNC paths
        raise LibraryError("only relative paths inside the library are allowed")
    root = root.resolve()
    target = (root / rel).resolve()
    if not target.is_relative_to(root):
        raise LibraryError("path escapes the library")
    for part in target.relative_to(root).parts:
        if part.split(".")[0].strip().upper() in RESERVED_NAMES:
            raise LibraryError("reserved device name")
    return target


def clean_title(title: str, fallback: str = "Draft") -> str:
    """Turn any string into a safe, readable filename stem."""
    title = re.sub(r"[^\w\s\-]", " ", str(title or ""), flags=re.UNICODE)
    title = re.sub(r"\s+", " ", title).strip(" .-_")[:60].strip()
    if not title:
        title = fallback
    if title.split(".")[0].upper() in RESERVED_NAMES:
        title = f"{title}-doc"
    return title


def _doc_id(kind: str, filename: str) -> str:
    digest = hashlib.sha1(filename.lower().encode("utf-8")).hexdigest()[:6]
    return f"{'src' if kind == 'source' else 'drf'}-{digest}"


def _paginate(text: str, words_per_page: int | None = None) -> list[str]:
    """Split text into pages of roughly N words, keeping paragraphs intact."""
    words_per_page = words_per_page or WORDS_PER_PAGE
    pages: list[str] = []
    current: list[str] = []
    count = 0
    for para in re.split(r"\n\s*\n", text):
        words = para.split()
        if not words:
            continue
        # a single giant paragraph gets split on word boundaries
        while len(words) > words_per_page:
            if current:
                pages.append("\n\n".join(current))
                current, count = [], 0
            pages.append(" ".join(words[:words_per_page]))
            words = words[words_per_page:]
            para = " ".join(words)
        if not words:
            continue
        if count + len(words) > words_per_page and current:
            pages.append("\n\n".join(current))
            current, count = [], 0
        current.append(para.strip())
        count += len(words)
    if current:
        pages.append("\n\n".join(current))
    return pages or [""]


def read_text(path: Path) -> str:
    return path.read_bytes().decode("utf-8-sig", errors="replace")


# --------------------------------------------------------------------------
# Library
# --------------------------------------------------------------------------


class Library:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).expanduser().resolve()
        for sub in (SOURCES, DRAFTS, HISTORY):
            (self.root / sub).mkdir(parents=True, exist_ok=True)

    # -- listing ------------------------------------------------------------

    def _scan(self, kind: str) -> list[Document]:
        folder = safe_path(self.root, SOURCES if kind == "source" else DRAFTS)
        docs = []
        for p in sorted(folder.iterdir(), key=lambda p: p.name.lower()):
            if p.is_symlink() or not p.is_file() or p.suffix.lower() not in ALLOWED_SUFFIXES:
                continue
            try:
                safe_path(self.root, f"{folder.name}/{p.name}")
            except LibraryError:
                continue
            docs.append(Document(_doc_id(kind, p.name), p.stem, kind, p))
        return docs

    def documents(self) -> list[Document]:
        return self._scan("source") + self._scan("draft")

    def get(self, doc_id: str) -> Document:
        """Look up a document by ID, or by exact title as a convenience.

        Either way the match is against the app's own listing of the library,
        so nothing the model passes in is ever used as a path.
        """
        doc_id = str(doc_id or "").strip()
        docs = self.documents()
        for doc in docs:
            if doc.id == doc_id:
                return doc
        named = [d for d in docs if d.title.lower() == doc_id.lower()]
        if len(named) == 1:
            return named[0]
        if len(named) > 1:
            ids = ", ".join(f"{d.id} ({d.kind})" for d in named)
            raise LibraryError(f"several documents are titled {doc_id!r}: {ids}; use the ID")
        raise LibraryError(f"no document with id or title {doc_id!r}")

    def describe(self) -> list[dict]:
        out = []
        for d in self.documents():
            text = read_text(d.path)
            out.append({
                "id": d.id,
                "title": d.title,
                "kind": d.kind,
                "filename": d.filename,
                "words": len(text.split()),
                "pages": len(_paginate(text)),
                "modified": datetime.fromtimestamp(d.path.stat().st_mtime).isoformat(timespec="seconds"),
            })
        return out

    # -- reading ------------------------------------------------------------

    def read_all(self, doc_id: str) -> tuple[Document, str]:
        doc = self.get(doc_id)
        return doc, read_text(doc.path)

    def read_page(self, doc_id: str, page: int = 1) -> tuple[Document, int, int, str]:
        doc, text = self.read_all(doc_id)
        pages = _paginate(text)
        try:
            page = int(page)
        except (TypeError, ValueError):
            page = 1
        page = min(max(page, 1), len(pages))
        return doc, page, len(pages), pages[page - 1]

    def search(self, query: str, limit: int = MAX_SEARCH_RESULTS) -> list[dict]:
        query = str(query or "").strip()
        if not query:
            raise LibraryError("empty search")
        terms = [t for t in re.findall(r"\w+", query.lower()) if len(t) >= 3]
        results = []
        for doc in self.documents():
            text = read_text(doc.path)
            low = text.lower()
            hits = [m.start() for m in re.finditer(re.escape(query.lower()), low)]
            if not hits and terms:
                hits = sorted({m.start() for t in terms for m in re.finditer(re.escape(t), low)})
            if not hits:
                continue
            pages = _paginate(text)
            for pos in hits[:2]:  # at most two snippets per document
                start, end = max(0, pos - 160), min(len(text), pos + 240)
                snippet = " ".join(text[start:end].split())
                words_before = len(text[:pos].split())
                page = min(words_before // WORDS_PER_PAGE + 1, len(pages))
                results.append({"id": doc.id, "title": doc.title, "page": page, "snippet": snippet})
            if len(results) >= limit:
                break
        return results[:limit]

    # -- writing (drafts only) --------------------------------------------

    def _check_content(self, content: str) -> str:
        content = str(content or "")
        if not content.strip():
            raise LibraryError("content is empty")
        if len(content.encode("utf-8")) > MAX_DRAFT_BYTES:
            raise LibraryError(f"content is larger than the {MAX_DRAFT_BYTES // 1000} KB draft limit")
        return content

    def create_draft(self, title: str, content: str) -> Document:
        content = self._check_content(content)
        if len(self._scan("draft")) >= MAX_DRAFTS:
            raise LibraryError(f"draft limit reached ({MAX_DRAFTS})")
        stem = clean_title(title)
        for n in range(1, 1000):
            name = f"{stem}.md" if n == 1 else f"{stem}-{n}.md"
            path = safe_path(self.root, f"{DRAFTS}/{name}")
            try:
                with open(path, "x", encoding="utf-8", newline="\n") as f:  # never overwrite
                    f.write(content)
            except FileExistsError:
                continue
            return Document(_doc_id("draft", name), path.stem, "draft", path)
        raise LibraryError("could not find a free filename")

    def revise_draft(self, doc_id: str, content: str) -> tuple[Document, Path]:
        content = self._check_content(content)
        doc = self.get(doc_id)
        if doc.kind != "draft":
            raise LibraryError(
                "sources are read-only; use create_draft to write a revised copy instead"
            )
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")
        backup = safe_path(self.root, f"{HISTORY}/{doc.path.stem}.{stamp}{doc.path.suffix}")
        shutil.copy2(doc.path, backup)
        tmp = safe_path(self.root, f"{DRAFTS}/.{doc.path.name}.tmp")
        tmp.write_text(content, encoding="utf-8", newline="\n")
        os.replace(tmp, doc.path)
        return doc, backup

    # -- user actions (called from the UI, never offered to the model) -----

    def import_files(self, paths: list[str]) -> dict:
        imported, skipped = [], []
        for raw in paths or []:
            src = Path(raw)
            if src.suffix.lower() not in ALLOWED_SUFFIXES:
                skipped.append({"file": src.name, "reason": "only .txt and .md files can be imported"})
                continue
            try:
                if not src.is_file():
                    raise LibraryError("not a file")
                if src.stat().st_size > MAX_IMPORT_BYTES:
                    raise LibraryError(f"larger than {MAX_IMPORT_BYTES // 1_000_000} MB")
                text = read_text(src)
                stem = clean_title(src.stem, fallback="Document")
                for n in range(1, 1000):
                    name = f"{stem}{src.suffix.lower()}" if n == 1 else f"{stem}-{n}{src.suffix.lower()}"
                    dest = safe_path(self.root, f"{SOURCES}/{name}")
                    try:
                        with open(dest, "x", encoding="utf-8", newline="\n") as f:
                            f.write(text)
                        break
                    except FileExistsError:
                        continue
                else:
                    raise LibraryError("could not find a free filename")
                imported.append(dest.stem)
            except (OSError, LibraryError) as e:
                skipped.append({"file": src.name, "reason": str(e)})
        return {"imported": imported, "skipped": skipped}

    def open_external(self, doc_id: str) -> None:
        doc = self.get(doc_id)
        os.startfile(safe_path(self.root, f"{doc.path.parent.name}/{doc.path.name}"))  # type: ignore[attr-defined]

    def open_folder(self) -> None:
        os.startfile(self.root)  # type: ignore[attr-defined]


def onedrive_warning(path: str | Path) -> str | None:
    """Return a warning if the path is inside a OneDrive-synced folder."""
    p = Path(path).expanduser().resolve()
    for var in ("OneDrive", "OneDriveConsumer", "OneDriveCommercial"):
        base = os.environ.get(var)
        if base and p.is_relative_to(Path(base).resolve()):
            return "This folder is synced by OneDrive, so documents here are uploaded to the cloud."
    if "onedrive" in (part.lower() for part in p.parts):
        return "This folder looks like it's inside OneDrive, so documents may be uploaded to the cloud."
    return None
